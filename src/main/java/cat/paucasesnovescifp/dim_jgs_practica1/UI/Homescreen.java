    private void refreshTable(){
        DefaultTableModel dtm = new DefaultTableModel();
        dtm.setColumnIdentifiers(new String [] {"Num. Registro", "Titulo del juego", "Usuario del préstamo", "Plataforma", "Fecha inicio", "Fecha devolución", "Devuelto?", "Género"});
        List<Borrow> list = BorrowList.getList();
        for (int i = list.size() - 1; i >= 0; i--){
            dtm.addRow(list.get(i).castToRow());
        }
        mainTable.setModel(dtm);
        colorRows(mainTable, BorrowList.getList());

        int rowCount = mainTable.getRowCount();
        rowCountLabel.setText("Numero de prestamos: " + rowCount);
    }

    public void colorRows(JTable mainTable, List<Borrow> borrowList) {
        DefaultTableCellRenderer statusRenderer = new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {

                Component cell = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                // Convert view index to model index to support user sorting
                int modelRow = table.convertRowIndexToModel(row);

                // Account for descending display order (last item inserted corresponds to top row)
                int listIndex = borrowList.size() - 1 - modelRow;

                if (listIndex >= 0 && listIndex < borrowList.size()) {
                    Borrow borrow = borrowList.get(listIndex);

                    if (!isSelected) {
                        if (borrow.isReturned()) {
                            cell.setBackground(new Color(200, 250, 200)); // Soft Green
                            cell.setForeground(Color.BLACK);
                        } else if (borrow.getEndDate() != null && LocalDateTime.now().isAfter(borrow.getEndDate())) {
                            cell.setBackground(new Color(250, 200, 200)); // Soft Red
                            cell.setForeground(Color.BLACK);
                        } else {
                            // Reset to standard background for non-expired, unreturned rows
                            cell.setBackground(table.getBackground());
                            cell.setForeground(table.getForeground());
                        }
                    }
                }

                return cell;
            }
        };

        // Apply the renderer across all columns in mainTable
        for (int i = 0; i < mainTable.getColumnCount(); i++) {
            mainTable.getColumnModel().getColumn(i).setCellRenderer(statusRenderer);
        }
    }
    
