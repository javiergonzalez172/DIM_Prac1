    private void confirmButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_confirmButtonMouseClicked
        if (nameField.getText().isEmpty()){
            errorLabel.setText("ERROR: El joc no té nom");
            return;
        }
        if (castGenre(genreField.getSelectedItem().toString()) == null){
            errorLabel.setText("ERROR: El joc no té gènere");
            return;
        }
        
        if (!ValidationAPI.checkString(nameField.getText())){
            errorLabel.setText("ERROR: La primera lletra del nom ha de ser majúscula");
            return;
        }
        
        List<PLATFORM> platformList = new ArrayList<>();
        List<Integer> unitList = new ArrayList<>();
        
        if (pcCheckbox.isSelected()){
            platformList.add(PLATFORM.PC);
            unitList.add((Integer)pcSpinner.getValue());
        }
        if (ps5Checkbox.isSelected()){
            platformList.add(PLATFORM.PS5);
            unitList.add((Integer)ps5Spinner.getValue());
        }
        if (xboxCheckbox.isSelected()){
            platformList.add(PLATFORM.XBOX);
            unitList.add((Integer)xboxSpinner.getValue());
        }
        if (switch2Checkbox.isSelected()){
            platformList.add(PLATFORM.SWITCH_2);
            unitList.add((Integer)switch2Spinner.getValue());
        }
        
        String genre = genreField.getSelectedItem().toString();
        Game game = new Game(nameField.getText(), castGenre(genre), platformList, unitList);
        GameList.add(game);
        
        this.setVisible(false);
        new Homescreen().setVisible(true);
    }//GEN-LAST:event_confirmButtonMouseClicked

