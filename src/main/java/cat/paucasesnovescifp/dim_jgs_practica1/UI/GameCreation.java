    private GENRE castGenre(String string){
        switch(string){
            case "RPG": return GENRE.RPG;
            case "SANDBOX": return GENRE.SANDBOX;
            case "ROGUELIKE": return GENRE.ROGUELIKE;
            case "MMO": return GENRE.MMO;
            case "VISUAL_NOVEL": return GENRE.VISUAL_NOVEL;
            case "STRATEGY": return GENRE.STRATEGY;
            case "SIMULATION": return GENRE.SIMULATION;
            case "SHOOTER": return GENRE.SHOOTER;
            case "FIGHTING": return GENRE.FIGHTING;
            case "PUZZLE": return GENRE.PUZZLE;
            case "SPORTS": return GENRE.SPORTS;
            case "RACING": return GENRE.RACING;
            default: return null;
        }
    }
    
