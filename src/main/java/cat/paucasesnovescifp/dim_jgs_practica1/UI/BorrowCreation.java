    private void confirmButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_confirmButtonMouseClicked
        User user = null;
        List<User> tempUserList = UserList.getList();
        for(int i = 0; i < tempUserList.size(); i++){
            if(tempUserList.get(i).getName().equals(userField.getSelectedItem())){
                user = tempUserList.get(i);
            }
        }
        if (user == null){
            errorLabel.setText("ERROR: Tens que seleccionar un usuari");
            return;
        }
        
        Game game = null;
        List<Game> tempGameList = GameList.getList();
        for(int i = 0; i < tempGameList.size(); i++){
            if(tempGameList.get(i).getName().equals(gameField.getSelectedItem())){
                game = tempGameList.get(i);
            }
        }
        if (game == null){
            errorLabel.setText("ERROR: Tens que seleccionar un joc");
            return;
        }
        
        PLATFORM platform;
        if (pcRadio.isSelected()){
            platform = PLATFORM.PC;
        } else if (ps5Radio.isSelected()){
            platform = PLATFORM.PS5;
        } else if (xboxRadio.isSelected()){
            platform = PLATFORM.XBOX;
        } else if (switch2Radio.isSelected()){
            platform = PLATFORM.SWITCH_2;
        } else {
            errorLabel.setText("ERROR: Tens que seleccionar una plataforma");
            return;
        }
        
        Borrow newBorrow = new Borrow(game, user, platform, LocalDateTime.now(), LocalDateTime.now().plus(1, ChronoUnit.WEEKS), false, game.getGenre());
        BorrowList.add(newBorrow);
        
        for(int i = 0; i < tempGameList.size(); i++){
            if(tempGameList.get(i).getName().equals(game.getName())){
                tempGameList.get(i).setCountSpecific(platform, (tempGameList.get(i).getCountSpecific(platform) - 1));
            }
        }
        
        this.setVisible(false);
        new Homescreen().setVisible(true);
    }//GEN-LAST:event_confirmButtonMouseClicked

