    private void refreshTable(){
        DefaultTableModel dtm = new DefaultTableModel();
        dtm.setColumnIdentifiers(new String [] {"Num. Registre", "Títol del joc", "Usuari del lloguer", "Plataforma", "Data d'inici", "Data de tornada", "Retornat?", "Gènere"});
        List<Borrow> list = BorrowList.getList();
        for (int i = list.size() - 1; i >= 0; i--){
            dtm.addRow(list.get(i).castToRow());
        }
        mainTable.setModel(dtm);
    }
    
    private void setMarked(int borrowIndex, boolean option){
        BorrowList.getList().get(borrowIndex).setReturned(option);
        
        int amount = option ? 1 : -1;
        List<Game> tempGameList = GameList.getList();
        for(int i = 0; i < tempGameList.size(); i++){
            if(tempGameList.get(i).getName().equals(BorrowList.getList().get(borrowIndex).getGame().getName())){ //Escoge el juego al que se debe editar las unidades
                PLATFORM platform = BorrowList.getList().get(borrowIndex).getPlatform(); //Escoge la plataforma de la unidad que toca
                tempGameList.get(i).setCountSpecific(platform, (tempGameList.get(i).getCountSpecific(platform) + amount)); //Cambia las unidades del juego en esa plataforma
            }
        }
    }
    
