    private void deleteButtonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_deleteButtonMouseClicked
        User user = updateInfo();
        if(user == null){
            errorLabel.setText("ERROR: Debe seleccionar un usuario");
            return;
        }
        
        List<Borrow> checkList = BorrowList.getList();
        for (int i = 0; i < checkList.size(); i++){
            if(user == checkList.get(i).getUser() && !checkList.get(i).isReturned()){
                errorLabel.setText("ERROR: No se puede eliminar un usuario con préstamos activos");
                return;
            }
        }
        
        List<User> list = UserList.getList();
        for (int i = 0; i < list.size(); i++){
            if(user == list.get(i)){
                list.remove(i);
            }
        }
        
        this.setVisible(false);
        new Homescreen().setVisible(true);
    }//GEN-LAST:event_deleteButtonMouseClicked

    private User updateInfo(){ //Hace de doble para actualizar la información y como getter
        List<User> list = UserList.getList();
        User user = null;
        for(int i = 0; i < list.size(); i++){
            if(list.get(i).getName().equals(userSelect.getSelectedItem())){
                user = list.get(i);
            }
        }
        nameField.setText("");
        surnamesField.setText("");
        dniField.setText("");
        phoneField.setText("");
        dateField.setText("");
        if(user != null){
            nameField.setText(user.getName());
            surnamesField.setText(user.getSurname1() + " " + user.getSurname2());
            dniField.setText(user.getDni());
            phoneField.setText(user.getPhone());
            dateField.setText(user.getDate().toString());
        }
        
        return user;
    }
    
