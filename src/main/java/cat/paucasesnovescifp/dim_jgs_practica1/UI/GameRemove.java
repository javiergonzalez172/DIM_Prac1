    private Game updateInfo(){ //Hace de doble para actualizar la información y como getter
        List<Game> list = GameList.getList();
        Game game = null;
        for(int i = 0; i < list.size(); i++){
            if(list.get(i).getName().equals(gameSelect.getSelectedItem())){
                game = list.get(i);
            }
        }
        nameField.setText("");
        genderField.setText("");
        pcField.setText("0");
        ps5Field.setText("0");
        xboxField.setText("0");
        switch2Field.setText("0");
        if(game != null){
            nameField.setText(game.getName());
            genderField.setText("" + game.getGenre());
            List<PLATFORM> platforms = game.getPlatforms();
            List<Integer> amounts = game.getCounts();
            for(int i = 0; i < platforms.size(); i++){
                if(platforms.get(i) == PLATFORM.PC && amounts.get(i) > 0){
                    pcField.setText("" + amounts.get(i));
                }
                if(platforms.get(i) == PLATFORM.PS5 && amounts.get(i) > 0){
                    ps5Field.setText("" + amounts.get(i));
                }
                if(platforms.get(i) == PLATFORM.XBOX && amounts.get(i) > 0){
                    xboxField.setText("" + amounts.get(i));
                }
                if(platforms.get(i) == PLATFORM.SWITCH_2 && amounts.get(i) > 0){
                    switch2Field.setText("" + amounts.get(i));
                }
            }
        }
        
        return game;
    }
    
